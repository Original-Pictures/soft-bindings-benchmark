"""Numbers of the v1.1 reruns, as \\val{v11:...} values (generated/v11/numbers.tex; assemble.py adds the prefix).

Reads only the v1.1 rerun records committed in the two tracks:
  fingerprinting/bench-2026-10/rerun-2026-11/results-drift/   ISCC drift on the 300 photos, this Mac, both versions
  fingerprinting/bench-2026-10/rerun-2026-11/results-wm/      TrustMark decoder vs detect-first, combination track
  watermarking/bench-2026-09/rerun-2026-11/results-detect/    TrustMark decoder vs detect-first, image track
A value is written only if its record exists, so text that cites a value whose rerun is still pending fails to
compile (\\val raises an error) instead of printing a stale or invented number.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
ROOT = HERE.parent
FP = ROOT / "fingerprinting" / "bench-2026-10" / "rerun-2026-11"
WM = ROOT / "watermarking" / "bench-2026-09" / "rerun-2026-11"


def pct(x: float, nd: int = 1) -> str:
    return f"{100 * x:.{nd}f}"


def main() -> None:
    v: dict[str, str] = {}
    for ver in ("0.9.5", "0.9.7"):
        p = FP / "results-drift" / f"drift-iscc-sdk-{ver}.json"
        if p.exists():
            d = json.loads(p.read_text())
            v[f"iscc/{ver}/n"] = str(d["n"])
            for m, r in d["methods"].items():
                v[f"iscc/{ver}/{m}/drift/pct"] = pct(r["drift_below_threshold"])
                v[f"iscc/{ver}/{m}/drift/k"] = str(r["n_below"])
                v[f"iscc/{ver}/{m}/threshold"] = f"{r['threshold']:.4f}"
    p = WM / "results-detect" / "summary.json"
    if p.exists():
        for cfg, s in json.loads(p.read_text()).items():
            for mode in ("decoder", "detect", "v1.0"):
                if mode not in s:
                    continue
                key = f"tm/{cfg}/{mode.replace('.', '')}"
                b = s[mode]["blind"]
                v[f"{key}/blind/k"], v[f"{key}/blind/n"] = str(b["k"]), str(b["n"])
                v[f"{key}/blind/pct"] = pct(b["rate"])
                v[f"{key}/blind/hi"] = pct(b["ci"][1])
                for a in ("none", "jpeg75", "crop70", "resize0.5", "_all"):
                    v[f"{key}/exact/{a.strip('_')}/pct"] = pct(s[mode]["exact"][a])
            if "decode_s_median" in s:
                for mode, t in s["decode_s_median"].items():
                    v[f"tm/{cfg}/{mode}/decode_s"] = f"{t:.2f}"
    p = FP / "results-wm" / "wm_detect300.json"
    if p.exists():
        d = json.loads(p.read_text())
        for mode, o in d["modes"].items():
            v[f"wmc/{mode}/key/pct"] = pct(o["wm_key_rate"])
            v[f"wmc/{mode}/npos"] = f"{o['n_pos']:,}".replace(",", "{,}")
            v[f"wmc/{mode}/falsekey/pct"] = pct(o["false_key_rate"], 2)
            v[f"wmc/{mode}/falsekey/n"] = f"{o['false_key_n']:,}".replace(",", "{,}")
            v[f"wmc/{mode}/falsekey/src"] = f"{o['false_key_sources']}/{o['n_neg_sources']}"
            for name in ("DINOv2-S", "ISC21-1st"):
                v[f"wmc/{mode}/{name}/either/pct"] = pct(o["union"][name]["either"], 0)
    out = HERE / "generated" / "v11" / "numbers.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("% Generated by scripts/v11_numbers.py from the v1.1 rerun records. Do not edit.\n" +
                   "".join(f"\\expandafter\\def\\csname val@{k}\\endcsname{{{x}}}\n" for k, x in sorted(v.items())))
    print(f"v11: {len(v)} values")


if __name__ == "__main__":
    main()
