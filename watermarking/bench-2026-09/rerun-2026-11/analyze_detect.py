"""Summarise bench_detectfirst.py records: TrustMark decoder-only versus detect-first, paired, next to the v1.0
GPU records of the same configs. Writes results-detect/DETECT.md and results-detect/summary.json.

Units follow the paper: robustness is the share of images whose exact payload is recovered (payload_exact) or
whose BCH layer reports a watermark (native_detect); the blind false-positive rate counts an unmarked image once
if the detector fired on any of its four decodes (none, jpeg75, resize0.5, crop70), with exact two-sided 95 %
Clopper-Pearson intervals over images.

    python3 analyze_detect.py      (needs scipy only)
"""
from __future__ import annotations

import gzip
import json
from pathlib import Path

from scipy.stats import beta

HERE = Path(__file__).resolve().parent
V10 = HERE.parent / "results-gpu" / "image"
KEY_ATTACKS = ["none", "jpeg75", "jpeg50", "webp60", "resize0.5", "crop90", "crop70", "crop50", "blur1", "bright0.8"]
EXCLUDE = {"image/hdr16/studio_small_09.tif"}  # local re-render differs from the manifest sha256 (tone mapping)


def cp(k: int, n: int) -> tuple[float, float]:
    lo = 0.0 if k == 0 else beta.ppf(0.025, k, n - k + 1)
    hi = 1.0 if k == n else beta.ppf(0.975, k + 1, n - k)
    return float(lo), float(hi)


def blind(fpr: list[dict], records: list[dict], key=None) -> dict:
    fired: dict[str, bool] = {}
    for t in fpr:
        item = records[t["item"]]["item"]
        if item in EXCLUDE:
            continue
        v = t[key]["native_detect"] if key else t["native_detect"]
        fired[item] = fired.get(item, False) or bool(v)
    k, n = sum(fired.values()), len(fired)
    hdr = [v for i, v in fired.items() if "/hdr16/" in i]
    return {"k": k, "n": n, "rate": k / n, "ci": cp(k, n), "hdr_k": sum(hdr), "hdr_n": len(hdr)}


def rates(records: list[dict], field: str, key=None) -> dict:
    out = {}
    for a in KEY_ATTACKS + ["_all"]:
        vals = []
        for r in records:
            if r["item"] in EXCLUDE or "attacks" not in r:
                continue
            for name, d in r["attacks"].items():
                if a in (name, "_all"):
                    vals.append(bool((d[key] if key else d).get(field)))
        out[a] = sum(vals) / len(vals) if vals else None
    return out


def main() -> None:
    summary, lines = {}, ["# TrustMark: decoder only versus detect first (v1.1, this Mac)", "",
                          "Generated by `rerun-2026-11/analyze_detect.py` from `results-detect/`. Same 85 images, payloads, "
                          "quantisation and attacks as the v1.0 image track; each attacked copy decoded both ways. "
                          "v1.0 = the paper's CUDA records (decoder only). One HDR item whose local tone-mapped file "
                          "differs from the manifest hash is left out of every column, so n = 84 images.", ""]
    for p in sorted(HERE.glob("results-detect/trustmark-*.json")):
        r = json.loads(p.read_text())
        name = r["config"]
        v10p = V10 / f"{name.replace('@', '_at_')}.json.gz"
        v10 = json.loads(gzip.decompress(v10p.read_bytes())) if v10p.exists() else None
        s = {"decode_s_median": r["decode_s_median"]}
        for mode in ("decoder", "detect"):
            s[mode] = {"exact": rates(r["records"], "payload_exact", mode), "detect": rates(r["records"], "native_detect", mode),
                       "blind": blind(r["fpr"], r["records"], mode)}
        if v10:
            s["v1.0"] = {"exact": rates(v10["records"], "payload_exact"), "detect": rates(v10["records"], "native_detect"),
                         "blind": blind(v10["fpr"], v10["records"])}
        summary[name] = s
        cols = [c for c in ("v1.0", "decoder", "detect") if c in s]
        lines += [f"## {name}", "", "| | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
        for a in KEY_ATTACKS + ["_all"]:
            lines.append(f"| exact payload, {a} | " + " | ".join(f"{100 * s[c]['exact'][a]:.1f}" for c in cols) + " |")
        b = {c: s[c]["blind"] for c in cols}
        lines.append("| blind false positives, images | " + " | ".join(
            f"{b[c]['k']}/{b[c]['n']} = {100 * b[c]['rate']:.1f} % [{100 * b[c]['ci'][0]:.1f}, {100 * b[c]['ci'][1]:.1f}]" for c in cols) + " |")
        lines.append("| of which HDR | " + " | ".join(f"{b[c]['hdr_k']}/{b[c]['hdr_n']}" for c in cols) + " |")
        lines.append("| median decode time on this Mac (CPU), s | " + " | ".join(
            "-" if c == "v1.0" else f"{s['decode_s_median'][c]:.2f}" for c in cols) + " |")
        lines.append("")
    (HERE / "results-detect" / "summary.json").write_text(json.dumps(summary, indent=1) + "\n")
    (HERE / "results-detect" / "DETECT.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
