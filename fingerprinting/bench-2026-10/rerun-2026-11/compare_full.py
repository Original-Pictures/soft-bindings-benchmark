"""Compare this Mac's full-scale ISCC image-track records (results-full/) with the reference records:
the paper's results-gpu/ for iscc-sdk 0.9.5 and the ISCC Foundation's results-iscc/iscc-sdk-0.9.7/ for 0.9.7.
Fields that cannot match by construction are skipped: host, timing, and disc21 (DISC21 is not on this machine).
Numbers are compared up to float32 rounding (iscc/compare.py's rule). Writes results-full/FULL.md.

    python3 compare_full.py
"""
from __future__ import annotations

import gzip
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
BENCH = HERE.parent
REF = {"0.9.5": BENCH / "results-gpu", "0.9.7": BENCH / "results-iscc" / "iscc-sdk-0.9.7"}
SKIP = {"host", "timing", "disc21", "disc21_source"}
OP = "pair@1e-07"


def rec(p: Path) -> dict | None:
    if p.exists():
        return json.loads(p.read_text())
    g = p.with_name(p.name + ".gz")
    return json.loads(gzip.decompress(g.read_bytes())) if g.exists() else None


def diffs(a, b, path=""):
    if isinstance(a, dict) and isinstance(b, dict):
        keys = sorted((a.keys() | b.keys()) - (SKIP if not path else set()))
        return [d for k in keys for d in diffs(a.get(k), b.get(k), f"{path}/{k}")]
    if isinstance(a, list) and isinstance(b, list) and len(a) == len(b):
        return [d for i, (x, y) in enumerate(zip(a, b)) for d in diffs(x, y, f"{path}[{i}]")]
    if isinstance(a, float) and isinstance(b, float):
        ok = (math.isnan(a) and math.isnan(b)) or math.isclose(a, b, rel_tol=1e-5, abs_tol=1e-9)
        return [] if ok else [path]
    return [] if a == b else [path]


def main() -> None:
    out = ["# ISCC image track at full scale on this Mac versus the reference records", "",
           "Generated by `rerun-2026-11/compare_full.py`. Reference: the paper's `results-gpu/` (iscc-sdk 0.9.5) and "
           "the ISCC Foundation's `results-iscc/iscc-sdk-0.9.7/`. Skipped: host, timing, DISC21 metrics (no DISC21 here). "
           "Rates in percent.", "",
           "| Method | iscc-sdk | Detected at 1e-7, this Mac | reference | Recall@1, this Mac | reference | fields compared that differ |",
           "|---|---|---|---|---|---|---|"]
    summary = {}
    for v in ("0.9.5", "0.9.7"):
        for m in ("ISCC-Image-64", "ISCC-Image-256"):
            mine = rec(HERE / "results-full" / f"iscc-sdk-{v}" / "image" / f"{m}.json")
            ref = rec(REF[v] / "image" / f"{m}.json")
            if mine is None or ref is None:
                continue
            d = diffs(mine, ref)
            t, tr = mine["per_attack"]["_all"][f"TPR@{OP}"], ref["per_attack"]["_all"][f"TPR@{OP}"]
            r, rr = mine["per_attack"]["_all"]["R@1"], ref["per_attack"]["_all"]["R@1"]
            summary[f"{v}/{m}"] = {"tpr7": t, "tpr7_ref": tr, "r1": r, "r1_ref": rr, "n_diff": len(d), "diff_paths": d[:50],
                                   "threshold": mine["thresholds"][OP], "threshold_ref": ref["thresholds"][OP],
                                   "per_attack_r1": {a: x["R@1"] for a, x in mine["per_attack"].items()}}
            out.append(f"| {m} | {v} | {100 * t:.1f} | {100 * tr:.1f} | {100 * r:.1f} | {100 * rr:.1f} | {len(d)} |")
    out += ["", "First differing fields (if any):", ""]
    for k, s in summary.items():
        if s["n_diff"]:
            out.append(f"- {k}: " + ", ".join(f"`{p}`" for p in s["diff_paths"][:8]))
    (HERE / "results-full" / "FULL.md").write_text("\n".join(out) + "\n")
    (HERE / "results-full" / "summary.json").write_text(json.dumps(summary, indent=1) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
