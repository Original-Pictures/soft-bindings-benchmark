"""Direction check of the ISCC update on the local smoke slice against the fork's full-scale records.

For each transformation: Recall@1 on the slice with iscc-sdk 0.9.5 and 0.9.7 (results-slice/, this machine)
and on the full image track (results-gpu/ for 0.9.5, the fork's results-iscc/iscc-sdk-0.9.7/ for 0.9.7).
A transformation "agrees" when the slice change and the full-scale change have the same sign, or when both
are within the slice's resolution (one query in 60 = 1.7 points). Writes results-slice/SLICE.md.

    python3 compare_slice.py
"""
from __future__ import annotations

import gzip
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BENCH = HERE.parent
METHODS = ("ISCC-Image-64", "ISCC-Image-256")
TIE = 1 / 60 + 1e-9  # one query of the 60 positive sources on the slice


def rec(path: Path) -> dict:
    return json.loads(path.read_text()) if path.exists() else json.loads(gzip.decompress(path.with_name(path.name + ".gz").read_bytes()))


def main() -> None:
    out = ["# ISCC update on the local smoke slice (direction check)", "",
           "Generated by `rerun-2026-11/compare_slice.py`. Slice: 1,720 ABO items (reg 120, dist 1,500, pos 60 x 36 "
           "transformations, neg 60 x 36, hard 30) on an Apple M5 Pro, harness unchanged, both ISCC versions. "
           "Full: the paper's records (0.9.5) and the ISCC Foundation's records (0.9.7), 2,000 sources x 36 "
           "transformations, 105k references. Recall@1 in percent. The slice cannot calibrate the pair-level 1e-7 "
           "threshold, so the headline operating point is not checked here.", ""]
    summary = []
    for m in METHODS:
        s5 = rec(HERE / "results-slice/iscc-sdk-0.9.5/image" / f"{m}.json")["per_attack"]
        s7 = rec(HERE / "results-slice/iscc-sdk-0.9.7/image" / f"{m}.json")["per_attack"]
        f5 = rec(BENCH / "results-gpu/image" / f"{m}.json")["per_attack"]
        f7 = rec(BENCH / "results-iscc/iscc-sdk-0.9.7/image" / f"{m}.json")["per_attack"]
        out += [f"## {m}", "", "| Transformation | slice 0.9.5 | slice 0.9.7 | slice change | full 0.9.5 | full 0.9.7 | full change | agrees |",
                "|---|---|---|---|---|---|---|---|"]
        agree = n = 0
        for a in sorted(s5, key=lambda k: (k != "_all", k)):
            ds, df = s7[a]["R@1"] - s5[a]["R@1"], f7[a]["R@1"] - f5[a]["R@1"]
            ok = (abs(ds) <= TIE and abs(df) <= 0.02) or (ds * df > 0) or (abs(ds) <= TIE and abs(df) <= TIE)
            if a != "_all":
                n += 1
                agree += ok
            out.append(f"| {a} | {100*s5[a]['R@1']:.1f} | {100*s7[a]['R@1']:.1f} | {100*ds:+.1f} | {100*f5[a]['R@1']:.1f} | "
                       f"{100*f7[a]['R@1']:.1f} | {100*df:+.1f} | {'yes' if ok else 'no'} |")
        out += ["", f"{agree} of {n} transformations agree in direction.", ""]
        summary.append(f"{m}: {agree}/{n}")
    (HERE / "results-slice" / "SLICE.md").write_text("\n".join(out) + "\n")
    print("; ".join(summary))


if __name__ == "__main__":
    main()
